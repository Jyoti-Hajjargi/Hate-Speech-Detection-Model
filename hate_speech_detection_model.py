def preprocess_text(text):
    text = text.lower()  # Converting the tweet in to lowercase
    text = re.sub(r'http\S+', '', text)  # Removing any URLs
    text = re.sub(r'@\w+', '', text)  # Removing any mentions
    text = re.sub(f"[{string.punctuation}]", '', text)  # Removing any punctuation
    text = re.sub(r'\d+', '', text)  # Removing the numerals
    text = ' '.join([word for word in text.split() if word not in stopwords.words('english')])  # Removing the stopwords or otherwise commonly used words (i.e.and, you, him, etc.)
    return text

