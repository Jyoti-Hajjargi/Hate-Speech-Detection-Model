def predict_text(text):
    # Use the defined function 'preprocess_text' instead of 'preprocess'
    clean = preprocess_text(text)
    # Tokenize the input text
    inputs = tokenizer(clean, return_tensors="pt", padding=True, truncation=True).to(device)

    # Get model predictions (logits)
    with torch.no_grad():
        outputs = model(**inputs)
        logits = outputs.logits

    # Get the predicted class
    pred = torch.argmax(logits, dim=1).item()  # Get the class index

    return label_map[pred]

