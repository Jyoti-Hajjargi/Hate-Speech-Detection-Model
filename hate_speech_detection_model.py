from transformers import BertTokenizer

tokenizer = BertTokenizer.from_pretrained('bert-base-uncased')

def tokenize_data(texts, labels, tokenizer, max_len=128):
    encodings = tokenizer(
        list(texts),
        truncation=True,
        padding=True,
        max_length=max_len,
        return_tensors="pt"
    )
    return encodings, labels

train_encodings, train_labels = tokenize_data(x_train, y_train, tokenizer)
test_encodings, test_labels = tokenize_data(x_test, y_test, tokenizer)

"""Preparing the dataset to use for the bert model trainging"""

import torch
from torch.utils.data import Dataset

class TweetDataset(Dataset):
    def __init__(self, encodings, labels):
        self.encodings = encodings
        self.labels = labels

    def __len__(self):
        return len(self.labels)

    def __getitem__(self, idx):
        item = {key: torch.tensor(val[idx]) for key, val in self.encodings.items()}
        item['labels'] = torch.tensor(self.labels.iloc[idx])
        return item
#Packaging the dataset for the model
train_dataset = TweetDataset(train_encodings, train_labels)
test_dataset = TweetDataset(test_encodings, test_labels)

"""Loading the BERT Model"""

from transformers import BertForSequenceClassification

#Loading the pre trained Bert Model
model = BertForSequenceClassification.from_pretrained(
    "bert-base-uncased",
    num_labels=3 # for classes hate speech, offensive language and neither
)

"""Initializing the Bert model"""

import torch
import torch.nn as nn
from torch.utils.data import DataLoader
from torch.optim import AdamW
from transformers import get_scheduler

#import torch_xla.core.xla_model as xm

# Create DataLoaders
train_loader = DataLoader(train_dataset, batch_size=16, shuffle=True)
test_loader = DataLoader(test_dataset, batch_size=16)

# Optimizer and Scheduler
optimizer = AdamW(model.parameters(), lr=5e-5)
num_training_steps = len(train_loader) * 3  # 3 epochs
lr_scheduler = get_scheduler("linear", optimizer=optimizer, num_warmup_steps=0, num_training_steps=num_training_steps)

# Set device
device = torch.device("cuda") if torch.cuda.is_available() else torch.device("cpu")

if torch.cuda.device_count() > 1:
    print(f"Using {torch.cuda.device_count()} GPUs!")
    model = nn.DataParallel(model)

#device = xm.xla_device()
model.to(device)

# Save model
torch.save(model.state_dict(), 'bert_hate_speech_model.pt')

# Load model (later)
model.load_state_dict(torch.load('bert_hate_speech_model.pt'))

"""Training the bert model"""

from tqdm import tqdm

# Training Loop
epochs = 3
progress_bar = tqdm(range(num_training_steps))

model.train()
for epoch in range(epochs):
    for batch in train_loader:
        batch = {key: val.to(device) for key, val in batch.items()}
        outputs = model(**batch)

        # Ensure the loss is reduced to a scalar
        loss = outputs.loss
        if loss.dim() > 0:  # If loss is not scalar
            loss = loss.mean()  # Reduce to a scalar

        # Backpropagation
        loss.backward()

        # Optimizer step and scheduler
        optimizer.step()
        lr_scheduler.step()
        optimizer.zero_grad()

        # Update progress bar
        progress_bar.update(1)

print("Training complete.")

